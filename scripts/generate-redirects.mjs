// scripts/generate-redirects.mjs
// Generates the root _redirects file from real archived data.
//
// Why this exists: the previous site was a static Astro build with
// /go/<slug>, /listings/<slug>, /category/<slug>, /vs/<slug1>-vs-<slug2>,
// /best and /support. The current site is a TanStack Start app serving
// /mcp/<slug>. GSC reports the old URLs as 404, which blocks AdSense review.
//
// Run: node scripts/generate-redirects.mjs
// Wired into package.json so `npm run build` always refreshes it.

import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");

const SITE = "https://agentstack.ink";

// --- Inputs -----------------------------------------------------------------

// Slugs of the listings that survived into the current editorial directory.
// Everything else in data/listings/ has no current equivalent.
const resourcesTs = readFileSync(resolve(ROOT, "src", "data", "resources.ts"), "utf8");
const liveSlugs = new Set(
  [...resourcesTs.matchAll(/^\s*id:\s*'([^']+)'/gm)].map((m) => m[1]),
);

// Every slug the archived Astro build ever published.
const archivedSlugs = readdirSync(resolve(ROOT, "data", "listings"))
  .filter((f) => f.endsWith(".json"))
  .map((f) => f.replace(/\.json$/, ""));

const archivedCategories = JSON.parse(
  readFileSync(resolve(ROOT, "data", "categories.json"), "utf8"),
).map((c) => c.slug);

// Pages the current app serves. Used for trailing-slash normalisation and to
// catch accidental self-redirects.
const livePages = [
  "/", "/about", "/changelog", "/contact", "/insights", "/learn",
  "/methodology", "/privacy", "/terms",
];

// Old top-level pages that no longer exist, with their closest current match.
const retiredPages = [
  ["/support", "/contact"],
  ["/best", "/"],
  ["/sponsor", "/"],
  ["/home", "/"],
  ["/rss.xml", "/sitemap.xml"],
];

// --- Output -----------------------------------------------------------------

const lines = [
  "# Cloudflare Pages redirects - generated by scripts/generate-redirects.mjs",
  "# Do not edit by hand; edit the generator and re-run it.",
  "#",
  "# The previous site was a static Astro build. These routes existed there and",
  "# 404 now, which shows up in Search Console and holds up AdSense review.",
  "#",
  "# Priority order matters: Cloudflare Pages applies the first matching rule.",
  "",];

// Collected rule sets, emitted both to _redirects and to the TypeScript module
// the SSR worker actually reads (see src/lib/legacy-redirect.ts).
const exact = new Map();
const wildcards = [];

const push = (from, to) => {
  lines.push(`${from.padEnd(32)} ${to.padEnd(20)} 301`);
  if (from.includes("*")) wildcards.push([from, to]);
  else exact.set(from, to);
};

// 1. Exact archived entry pages that still exist under /mcp/. These are the
//    highest-value redirects because they preserve the original destination.
lines.push("# --- Archived entry pages that still exist, now under /mcp/ ---");
for (const slug of archivedSlugs.filter((s) => liveSlugs.has(s)).sort()) {
  push(`/go/${slug}`, `/mcp/${slug}`);
  push(`/listings/${slug}`, `/mcp/${slug}`);
}

// 2. Archived entry pages with no current equivalent. Sending them to the
//    directory index tells Google the content is gone and consolidates
//    whatever equity is left onto the homepage.
lines.push("", "# --- Archived entries with no current review (directory index) ---");
for (const slug of archivedSlugs.filter((s) => !liveSlugs.has(s)).sort()) {
  push(`/go/${slug}`, "/");
  push(`/listings/${slug}`, "/");
}

// 3. Categories were filter states on the old homepage, never standalone pages.
lines.push("", "# --- Archived categories (filters now live on the homepage) ---");
for (const slug of archivedCategories.sort()) {
  push(`/category/${slug}`, "/");
}

// 4. Comparison pages ("a-vs-b"). The current site has no comparison route;
//    /learn is the closest educational equivalent.
lines.push("", "# --- Archived comparison pages ---");
push("/vs/*", "/learn");

// 5. Retired top-level pages.
lines.push("", "# --- Retired top-level pages ---");
for (const [from, to] of retiredPages) push(from, to);

// 6. Trailing-slash normalisation. TanStack Start answers /page/ with a 307,
//    which Google treats as a temporary move. A 301 is the correct signal.
lines.push("", "# --- Trailing slash -> canonical (framework default is a 307) ---");
for (const page of livePages) {
  if (page === "/") continue;
  push(`${page}/`, page);
}
for (const slug of liveSlugs) push(`/mcp/${slug}/`, `/mcp/${slug}`);

lines.push("", "");

const out = resolve(ROOT, "_redirects");
writeFileSync(out, lines.join("\n"), "utf8");

// --- TypeScript module ------------------------------------------------------
// The Pages build emits a `_worker.js`, and when that worker is present
// Cloudflare hands every request to it instead of consulting `_redirects`.
// The worker therefore needs the same rules as data it can import directly.
// See src/lib/legacy-redirect.ts and src/server.ts.

const tsLines = [
  "// AUTO-GENERATED by scripts/generate-redirects.mjs - do not edit by hand.",
  "//",
  "// Legacy URL map applied at the edge by src/lib/legacy-redirect.ts.",
  "// Mirrors the root _redirects file. The worker reads this one because a",
  "// Cloudflare Pages `_worker.js` build bypasses `_redirects` entirely.",
  "",
  "export const EXACT_REDIRECTS: Record<string, string> = {",
  ...[...exact.entries()].map(([from, to]) => `  ${JSON.stringify(from)}: ${JSON.stringify(to)},`),
  "};",
  "",
  "/** Patterns containing `*`; the captured segment is substituted into the target. */",
  "export const WILDCARD_REDIRECTS: Array<[string, string]> = [",
  ...wildcards.map(([from, to]) => `  [${JSON.stringify(from)}, ${JSON.stringify(to)}],`),
  "];",
  "",
];

const tsOut = resolve(ROOT, "src", "generated", "redirects.ts");
mkdirSync(dirname(tsOut), { recursive: true });
writeFileSync(tsOut, tsLines.join("\n"), "utf8");

const count = lines.filter((l) => l.trim().endsWith("301")).length;
console.log(
  `OK: wrote ${count} redirect rules to ${out}\n` +
  `    and ${exact.size} exact + ${wildcards.length} wildcard rules to ${tsOut}\n` +
  `    ${liveSlugs.size} surviving slugs, ` +
  `${archivedSlugs.length - liveSlugs.size} retired entries, ` +
  `${archivedCategories.length} categories, ${livePages.length - 1} trailing-slash fixes`,
);